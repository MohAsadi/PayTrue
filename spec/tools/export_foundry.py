COVER = re.compile(r"(MIG|ACP|CAP)-TV-(\d+)((?:\s*,\s*\d+)*)")


def covered_ids(text):
    out = set()
    for m in COVER.finditer(text):
        fam = m.group(1)
        out.add(f"{fam}-TV-{int(m.group(2)):02d}")
        out.add(f"{fam}-TV-{int(m.group(2))}")
        for extra in re.findall(r"\d+", m.group(3) or ""):
            out.add(f"{fam}-TV-{int(extra):02d}")
            out.add(f"{fam}-TV-{int(extra)}")
    # ranges such as "ACP-TV-13..17" or "ACP-TV-41..44"
    for fam, a, b in re.findall(r"(MIG|ACP|CAP)-TV-(\d+)\.\.(\d+)", text):
        for n in range(int(a), int(b) + 1):
            out.add(f"{fam}-TV-{n:02d}")
            out.add(f"{fam}-TV-{n}")
    return out


def coverage(suite):
    cov = {}
    for v in suite["scenarios"]:
        for i in covered_ids(v.source + " " + v.title):
            cov.setdefault(i, []).append(v.id)
    for vid, src, label, _w in suite["terms"]:
        for i in covered_ids(src + " " + label) | ({src} if src.startswith("K.") else set()):
            cov.setdefault(i, []).append(vid)
        for k in re.findall(r"K\.\d", label):
            cov.setdefault(k, []).append(vid)
    for b in suite["backend"]:
        for i in covered_ids(b["source"] + " " + b["title"]):
            cov.setdefault(i, []).append(b["id"])
    cov.setdefault("MIG-TV-19", []).append("hashes.test_PaymentIdIsRouterIndependent")
    return cov


