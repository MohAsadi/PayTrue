def mutant_numbers_in_sources():
    """Every mutant constant of src/Mutants.sol that the hand-written model uses; reported by --verify (a mutant the Solidity model never
    reads can never be killed there)."""
    used, unused = set(), []
    src = FOUNDRY / "src"
    text = "".join(p.read_text(encoding="utf-8") for p in sorted(src.glob("*.sol")) if p.name != "Mutants.sol") if src.exists() else ""
    for _i, name, _d in M.MUTANTS:
        if re.search(rf"\bM_{name}\b", text):
            used.add(name)
        else:
            unused.append(name)
    return used, unused


def main():
    write, verify = "--write" in sys.argv, "--verify" in sys.argv
    if not (write or verify):
        print("use --write or --verify")
        return 2
    files, suite, cov = build_files()
    bad = []
    for rel, text in sorted(files.items()):
        path = FOUNDRY / rel
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
        else:
            have = path.read_bytes().decode("utf-8") if path.exists() else None
            if have is None or have.replace("\r\n", "\n") != text:
                bad.append(rel)
    n_scen, n_terms = len(suite["scenarios"]), len(suite["terms"])
    per = {}
    for v in suite["scenarios"]:
        per[v.source] = per.get(v.source, 0) + 1
    if write:
        print(f"wrote {len(files)} files under spec/foundry: {n_scen} scenarios, {n_terms} containment tuples, "
              f"{sum(len(t['transitions']) for t in suite['tables'].values())} table transitions, {len(M.MUTANTS)} mutants")
        return 0
    used, unused = mutant_numbers_in_sources()
    if bad:
        print("out of date:", ", ".join(bad))
        return 1
    if unused:
        print(f"export up to date ({len(files)} files); note: {len(unused)} mutants are not read by the Solidity model yet: {', '.join(unused[:6])}"
              f"{' ...' if len(unused) > 6 else ''}")
        return 1
    print(f"export up to date: {len(files)} files, {n_scen} scenarios, {n_terms} containment tuples, "
          f"{sum(len(t['transitions']) for t in suite['tables'].values())} table transitions, all {len(M.MUTANTS)} mutants wired in the Solidity model")
    return 0


if __name__ == "__main__":
    sys.exit(main())
