# ----------------------------------------------------------------------------------------------------------------- JSON
def jdump(obj, level=0):
    """Canonical JSON: sorted keys, one key per line, arrays of scalars wrapped at 110 characters. Integers above 2^53 are strings."""
    pad = "  " * level
    if isinstance(obj, dict):
        if not obj:
            return "{}"
        items = [f'{pad}  {json.dumps(k)}: {jdump(v, level + 1)}' for k, v in sorted(obj.items())]
        return "{\n" + ",\n".join(items) + "\n" + pad + "}"
    if isinstance(obj, (list, tuple)):
        if not obj:
            return "[]"
        if all(isinstance(x, (str, int, bool)) or x is None for x in obj):
            parts = [json.dumps(x) for x in obj]
            lines, cur = [], ""
            for p in parts:
                if cur and len(cur) + len(p) + 2 > 110:
                    lines.append(cur)
                    cur = ""
                cur = (cur + ", " if cur else "") + p
            lines.append(cur)
            if len(lines) == 1:
                return "[" + lines[0] + "]"
            return "[\n" + ",\n".join(f"{pad}  {ln}" for ln in lines) + "\n" + pad + "]"
        return "[\n" + ",\n".join(f"{pad}  {jdump(x, level + 1)}" for x in obj) + "\n" + pad + "]"
    if isinstance(obj, bool):
        return "true" if obj else "false"
    if isinstance(obj, int):
        return json.dumps(obj if abs(obj) < (1 << 53) else str(obj))
    if obj is None:
        return "null"
    return json.dumps(obj)


def words(ws):
    """A flat array of uint256 words as decimal strings (Foundry parses an array of numeric strings as uint256[])."""
    return [str(w) for w in ws]


