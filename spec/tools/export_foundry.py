def errors_sol():
    out = [header("tools/protocol_model.py (ERRORS)"),
           "// Custom errors of documents 11, 12 and 17 (names as in the documents) and of Permit2 (AllowanceTransfer at the pinned commit).",
           "// Names marked `invented` in tools/protocol_model.py are not named by the documents (see the document issues in the report).", ""]
    for name, sig, _idx, _kind in M.ERRORS:
        if name == "Panic":
            continue
        args = sig[sig.index("(") + 1:-1]
        if args:
            types = [t.strip() for t in args.split(",")]
            names = TOKEN_ARG_NAMES[name].split(",")
            if len(types) == 1:
                decl = f"{types[0]} {TOKEN_ARG_NAMES[name]}"
            else:
                decl = f"{types[0]} {names[0].strip()}, {names[1].strip()}"
            out.append(f"error {name}({decl});")
        else:
            out.append(f"error {name}();")
    out.append("")
    return "\n".join(out)


