def const_name(n):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", n).upper()


# ------------------------------------------------------------------------------------------------------------------ Solidity
def sol_member_type(t):
    return t[:-2] + "[]" if t.endswith("[]") else t


def gen_solidity(reg):
    doc = reg.doc
    L = ["// SPDX-License-Identifier: Apache-2.0", "pragma solidity 0.8.24;", "", f"// {HEADER}",
         f"// Source: eip712/types.json (spec {doc['specVersion']}, status {doc['status']}: not frozen until the freeze register says so).",
         "// Every array that is hashed is bounded by a named constant (PC-04, PC-11): hashing is O(bound), never unbounded.", "",
         "library FastPayTypes {",
         "    error ArrayTooLong(uint256 length, uint256 max);", ""]
    for k, b in doc["bounds"].items():
        L.append(f"    uint256 internal constant {k} = {b['value']}; // {b['record']}")
    L.append("")
    L.append("    // ---- domains")
    L.append(f'    string internal constant DOMAIN_TYPE = "{doc["domainType"]}";')
    L.append("    bytes32 internal constant DOMAIN_TYPEHASH = keccak256(bytes(DOMAIN_TYPE));")
    for k, d in doc["domains"].items():
        L.append(f'    string internal constant {k.upper()}_DOMAIN_NAME = "{d["name"]}";')
        L.append(f'    string internal constant {k.upper()}_DOMAIN_VERSION = "{d["version"]}";')
    L.append("")
    L.append("    // ---- tags (bytes32 constants are keccak256 of the ASCII string)")
    for k, s in doc["tags"].items():
        L.append(f'    bytes32 internal constant {k} = keccak256("{s}");')
    L.append("")
    L.append("    // ---- structs (field order is the order of the type string)")
    for s in doc["structs"]:
        L.append(f"    struct {s['name']} {{")
        for t, n in s["fields"]:
            L.append(f"        {sol_member_type(t)} {n};")
        L.append("    }")
    L.append("")
    L.append("    // ---- type strings: encodeType, with the referenced structs appended in alphabetical order")
    for s in doc["structs"]:
        c = const_name(s["name"])
        L.append(f'    string internal constant {c}_TYPE =')
        L.append(f'        "{reg.encode_type(s["name"])}";')
        L.append(f"    bytes32 internal constant {c}_TYPEHASH = keccak256(bytes({c}_TYPE));")
    L.append("")
    w = doc["permit2Witness"]
    L.append("    // ---- the Permit2 witness (SignatureTransfer): the router passes witness = hashStruct(PayOnceIntent) and this string")
    L.append(f'    string internal constant PAY_ONCE_WITNESS_TYPESTRING =')
    L.append(f'        "{reg.witness_type_string()}";')
    L.append(f'    string internal constant PERMIT2_STUB_WITNESS_SINGLE =')
    L.append(f'        "{w["stubSingle"]}";')
    L.append(f'    string internal constant PERMIT2_STUB_WITNESS_BATCH =')
    L.append(f'        "{w["stubBatch"]}";')
    L.append('    string internal constant TOKEN_PERMISSIONS_TYPE = "' + w["tokenPermissions"] + '";')
    L.append("    bytes32 internal constant TOKEN_PERMISSIONS_TYPEHASH = keccak256(bytes(TOKEN_PERMISSIONS_TYPE));")
    L.append("    bytes32 internal constant PERMIT2_WITNESS_TRANSFER_FROM_TYPEHASH =")
    L.append("        keccak256(abi.encodePacked(PERMIT2_STUB_WITNESS_SINGLE, PAY_ONCE_WITNESS_TYPESTRING));")
    L.append("    bytes32 internal constant PERMIT2_BATCH_WITNESS_TRANSFER_FROM_TYPEHASH =")
    L.append("        keccak256(abi.encodePacked(PERMIT2_STUB_WITNESS_BATCH, PAY_ONCE_WITNESS_TYPESTRING));")
    L.append(f'    string internal constant PERMIT2_DOMAIN_TYPE = "{w["domain"]["type"]}";')
    L.append(f'    string internal constant PERMIT2_DOMAIN_NAME = "{w["domain"]["name"]}";')
    L.append("")
    L.append("    // ---- domain separators and digests")
    L.append("    function domainSeparator(string memory name, string memory version, uint256 chainId, address verifyingContract)")
    L.append("        internal pure returns (bytes32)")
    L.append("    {")
    L.append("        return keccak256(abi.encode(DOMAIN_TYPEHASH, keccak256(bytes(name)), keccak256(bytes(version)), chainId, verifyingContract));")
    L.append("    }")
    L.append("")
    L.append("    function mandatesDomainSeparator(uint256 chainId, address mandateManager) internal pure returns (bytes32) {")
    L.append("        return domainSeparator(MANDATES_DOMAIN_NAME, MANDATES_DOMAIN_VERSION, chainId, mandateManager);")
    L.append("    }")
    L.append("")
    L.append("    function quoteDomainSeparator(uint256 chainId, address router) internal pure returns (bytes32) {")
    L.append("        return domainSeparator(QUOTE_DOMAIN_NAME, QUOTE_DOMAIN_VERSION, chainId, router);")
    L.append("    }")
    L.append("")
    L.append("    /// Permit2's own domain: name \"Permit2\", no version (Permit2 src/EIP712.sol).")
    L.append("    function permit2DomainSeparator(uint256 chainId, address permit2) internal pure returns (bytes32) {")
    L.append("        return keccak256(abi.encode(keccak256(bytes(PERMIT2_DOMAIN_TYPE)), keccak256(bytes(PERMIT2_DOMAIN_NAME)), chainId, permit2));")
    L.append("    }")
    L.append("")
    L.append("    function digest(bytes32 separator, bytes32 structHash) internal pure returns (bytes32) {")
    L.append('        return keccak256(abi.encodePacked("\\x19\\x01", separator, structHash));')
    L.append("    }")
    L.append("")
    L.append("    // ---- hashStruct")
    helpers_done = set()
    for s in doc["structs"]:
        n, c = s["name"], const_name(s["name"])
        bounded = s.get("boundedArrays", {})
        for t, f in s["fields"]:
            if t.endswith("[]"):
                assert f in bounded, f"{n}.{f}: every array that is hashed needs a declared bound (boundedArrays)"
                if t[:-2] in reg.structs and t[:-2] not in helpers_done:
                    b = t[:-2]
                    helpers_done.add(b)
        L.append(f"    function hashStruct({n} memory s) internal pure returns (bytes32) {{")
        for t, f in s["fields"]:
            if t.endswith("[]"):
                L.append(f"        if (s.{f}.length > {bounded[f]}) revert ArrayTooLong(s.{f}.length, {bounded[f]});")
        args = [f"{c}_TYPEHASH"]
        for t, f in s["fields"]:
            if t.endswith("[]"):
                base = t[:-2]
                args.append(f"hashStructs(s.{f})" if base in reg.structs else f"keccak256(abi.encodePacked(s.{f}))")
            elif t in reg.structs:
                args.append(f"hashStruct(s.{f})")
            else:
                args.append(f"s.{f}")
        if len(args) <= 9:
            L.append("        return keccak256(abi.encode(" + ", ".join(args) + "));")
        else:
            # every argument is one static word (a dynamic member is already its hash), so the encoding of the chunks concatenated equals the
            # encoding of the whole; the chunks keep the stack of a 16-field struct (PriceQuote) under the limit of the non-IR compiler
            chunks = [args[i:i + 8] for i in range(0, len(args), 8)]
            for i, ch in enumerate(chunks):
                L.append(f"        bytes memory c{i} = abi.encode({', '.join(ch)});")
            L.append("        return keccak256(bytes.concat(" + ", ".join(f"c{i}" for i in range(len(chunks))) + "));")
        L.append("    }")
        L.append("")
    for b in sorted(helpers_done):
        sym = next(bd for s in doc["structs"] for tt, ff in s["fields"] if tt == b + "[]" for bd in [s["boundedArrays"][ff]])
        cls = {"MAX_TOKENS_PER_MANDATE": "TOKENS", "MAX_BATCH": "BATCH"}[sym]
        L.append(f"    /// Loop bound: the caller has already checked the length against {sym} (ArrayTooLong).")
        L.append(f"    function hashStructs({b}[] memory a) internal pure returns (bytes32) {{")
        L.append("        bytes32[] memory h = new bytes32[](a.length);")
        L.append(f"        // loop-bound: {cls} | a.length <= {sym} | hashStruct of the struct that owns the array reverts ArrayTooLong above the bound before it calls this function (the generator refuses an array without a declared bound)")
        L.append("        for (uint256 i; i < a.length; ++i) h[i] = hashStruct(a[i]);")
        L.append("        return keccak256(abi.encodePacked(h));")
        L.append("    }")
        L.append("")
    L += gen_snapshot_solidity(doc)
    L.append("    // ---- Permit2 witness hashes exactly as Permit2 computes them (PermitHash.sol at the pinned commit)")
    L.append("    function permit2WitnessTransferFromHash(address token, uint256 amount, address spender, uint256 nonce, uint256 deadline,")
    L.append("        PayOnceIntent memory intent) internal pure returns (bytes32)")
    L.append("    {")
    L.append("        bytes32 tp = keccak256(abi.encode(TOKEN_PERMISSIONS_TYPEHASH, token, amount));")
    L.append("        return keccak256(abi.encode(PERMIT2_WITNESS_TRANSFER_FROM_TYPEHASH, tp, spender, nonce, deadline, hashStruct(intent)));")
    L.append("    }")
    L.append("")
    L.append("    /// `permitted` is the array of (token, amount) pairs of the batch; the batch is bounded by the caller (at most MAX_WITNESS_BATCH = 2 in Router v1.0).")
    L.append("    function permit2BatchWitnessTransferFromHash(address[] memory tokens, uint256[] memory amounts, address spender, uint256 nonce,")
    L.append("        uint256 deadline, PayOnceIntent memory intent) internal pure returns (bytes32)")
    L.append("    {")
    L.append("        require(tokens.length == amounts.length && tokens.length <= MAX_WITNESS_BATCH, \"batch\");")
    L.append("        bytes32[] memory h = new bytes32[](tokens.length);")
    L.append("        // loop-bound: WITNESS_BATCH | tokens.length <= MAX_WITNESS_BATCH | the require above bounds the batch (Router v1.0: merchant and fee)")
    L.append("        for (uint256 i; i < tokens.length; ++i) h[i] = keccak256(abi.encode(TOKEN_PERMISSIONS_TYPEHASH, tokens[i], amounts[i]));")
    L.append("        bytes32 tp = keccak256(abi.encodePacked(h));")
    L.append("        return keccak256(abi.encode(PERMIT2_BATCH_WITNESS_TRANSFER_FROM_TYPEHASH, tp, spender, nonce, deadline, hashStruct(intent)));")
    L.append("    }")
    L.append("}")
    return "\n".join(L) + "\n"


def gen_snapshot_solidity(doc):
    """termsSnapshotHash (document 12 section 5.3.2) from eip712/types.json snapshotEncoding: the words in chunks of eight so that the
    function needs no via-IR, and the two digests over the tokens of the terms."""
    se = doc["snapshotEncoding"]
    expr = []
    for _name, src in se["words"]:
        kind, _, f = src.partition(":")
        expr.append({"tag": "SNAPSHOT_TAG", "arg": f, "terms": "t." + f, "terms.fiat": "t.fiat." + f,
                     "digest": "_tokensDigest(t.tokens)" if f == "tokens" else "_capTableDigest(t.tokens)"}[kind])
    chunks = [expr[i:i + 8] for i in range(0, len(expr), 8)]
    L = ["    // ---- termsSnapshotHash: the words of eip712/types.json snapshotEncoding, in that order (one 32-byte word each)",
         "    function snapshotHash(bytes32 lineageId, bytes32 predecessorId, uint32 generation, address customer, MandateTerms memory t)",
         "        internal pure returns (bytes32)", "    {",
         "        if (t.tokens.length > MAX_TOKENS_PER_MANDATE) revert ArrayTooLong(t.tokens.length, MAX_TOKENS_PER_MANDATE);"]
    for i, c in enumerate(chunks):
        L.append(f"        bytes memory c{i} = abi.encode({', '.join(c)});")
    L.append("        return keccak256(bytes.concat(" + ", ".join(f"c{i}" for i in range(len(chunks))) + "));")
    L.append("    }")
    L.append("")
    L.append("    function _tokensDigest(TokenTerms[] memory ts) private pure returns (bytes32) {")
    L.append("        bytes memory x;")
    L.append("        // loop-bound: TOKENS | ts.length <= MAX_TOKENS_PER_MANDATE | snapshotHash reverts ArrayTooLong above the bound before it calls this function")
    L.append("        for (uint256 i; i < ts.length; ++i) x = bytes.concat(x, abi.encode(ts[i].token));")
    L.append("        return keccak256(x);")
    L.append("    }")
    L.append("")
    L.append("    function _capTableDigest(TokenTerms[] memory ts) private pure returns (bytes32) {")
    L.append("        bytes memory x;")
    L.append("        // loop-bound: TOKENS | ts.length <= MAX_TOKENS_PER_MANDATE | snapshotHash reverts ArrayTooLong above the bound before it calls this function")
    words = ", ".join(f"ts[i].{f}" for f in se["tokenWords"])
    L.append(f"        for (uint256 i; i < ts.length; ++i) x = bytes.concat(x, abi.encode({words}));")
    L.append("        return keccak256(x);")
    L.append("    }")
    L.append("")
    return L


# ------------------------------------------------------------------------------------------------------------------ Solidity test with golden literals
class Builder:
    def __init__(self, reg):
        self.reg = reg
        self.funcs = []
        self.n = 0

    def lit(self, t, v):
        if t == "address":
            return f'address(bytes20(hex"{v[2:].lower()}"))'
        if t.startswith("bytes"):
            return f'bytes32(hex"{v[2:]}")' if t == "bytes32" else f'{t}(hex"{v[2:]}")'
        if t == "bool":
            return "true" if v else "false"
        return str(int(v))

    def build(self, name, value):
        """Emit a function that builds `value` of struct `name`; returns its name."""
        self.n += 1
        fn = f"_b{self.n}_{name}"
        body = [f"    function {fn}() internal pure returns (T.{name} memory v) {{"]
        for t, f in self.reg.structs[name]["fields"]:
            v = value[f]
            if t.endswith("[]"):
                base = t[:-2]
                body.append(f"        v.{f} = new {sol_member_type(base) if base not in self.reg.structs else 'T.' + base}[]({len(v)});")
                for i, e in enumerate(v):
                    if base in self.reg.structs:
                        body.append(f"        v.{f}[{i}] = {self.build(base, e)}();")
                    else:
                        body.append(f"        v.{f}[{i}] = {self.lit(base, e)};")
            elif t in self.reg.structs:
                body.append(f"        v.{f} = {self.build(t, v)}();")
            else:
                body.append(f"        v.{f} = {self.lit(t, v)};")
        body.append("    }")
        self.funcs.append("\n".join(body))
        return fn


