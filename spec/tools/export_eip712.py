def gen_ts(reg, golden):
    doc = reg.doc
    L = [f"// {HEADER}", "// The TypeScript side of the FastPay typed data; the encoder is fastpay-eip712.ts, the test is test-eip712.ts.", "",
         "export type Field = readonly [type: string, name: string];", "",
         f"export const STATUS = {json.dumps(doc['status'])};", f"export const SPEC_VERSION = {json.dumps(doc['specVersion'])};", "",
         f"export const DOMAIN_TYPE = {json.dumps(doc['domainType'])};", "",
         "export const DOMAINS = " + json.dumps({k: {"name": d["name"], "version": d["version"]} for k, d in doc["domains"].items()}, indent=2) + " as const;", "",
         "export const BOUNDS = " + json.dumps({k: b["value"] for k, b in doc["bounds"].items()}, indent=2) + " as const;", "",
         "export const TAGS = " + json.dumps(doc["tags"], indent=2) + " as const;", "",
         "export const STRUCTS: Record<string, { domain: string; fields: readonly Field[]; boundedArrays: Record<string, string> }> = {"]
    for s in doc["structs"]:
        L.append(f"  {s['name']}: {{ domain: {json.dumps(s['domain'])}, boundedArrays: {json.dumps(s.get('boundedArrays', {}))}, fields: [")
        for t, f in s["fields"]:
            L.append(f"    [{json.dumps(t)}, {json.dumps(f)}],")
        L.append("  ] },")
    L.append("};")
    L.append("")
    w = doc["permit2Witness"]
    L.append("export const PERMIT2_WITNESS = " + json.dumps({k: w[k] for k in ("witness", "witnessField", "tokenPermissions", "stubSingle", "stubBatch")} | {"domainType": w["domain"]["type"], "domainName": w["domain"]["name"]}, indent=2) + " as const;")
    L.append("")
    se = doc["snapshotEncoding"]
    L.append("export const SNAPSHOT = " + json.dumps({"words": se["words"], "tokenWords": se["tokenWords"]}, indent=2) + " as const;")
    L.append("")
    L.append("// Type hashes as generated by the Python reference encoder; the test recomputes every one of them.")
    L.append("export const TYPEHASHES: Record<string, string> = {")
    for s in doc["structs"]:
        L.append(f"  {s['name']}: {json.dumps(golden['structs'][s['name']]['typeHash'])},")
    L.append("};")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------------------------------------------------------ Markdown
def gen_md(reg, golden):
    doc = reg.doc
    L = ["# FastPay EIP-712 types (generated)", "", f"> {HEADER}", "",
         f"Specification {doc['specVersion']}. Status: **{doc['status']}** — {doc['statusNote']}", "",
         f"Freeze fingerprint (SHA-256 of every string below, without prose; condition C-11 of `tools/freeze_readiness.py` compares an approval with it): `{golden['freezeFingerprintSha256']}`", "",
         "## Domains", "", "| Domain | name | version | verifyingContract | separator on the vector chain/contract |", "|---|---|---|---|---|"]
    for k, d in doc["domains"].items():
        g = golden["domains"][k]
        L.append(f"| `{k}` | `{d['name']}` | `{d['version']}` | `{d['verifyingContract']}` | `{g['separator']}` |")
    L += ["", f"`EIP712Domain` type: `{doc['domainType']}`. Permit2's domain (for the Pay Once witness): `{doc['permit2Witness']['domain']['type']}` with name `Permit2`.",
          "", "## Type strings", "", "Each string is `encodeType` (the primary type, then every referenced struct sorted by name). Status: QUOTED = copied from the cited document; DERIVED = assembled from the field lists of the cited documents.", ""]
    for s in doc["structs"]:
        g = golden["structs"][s["name"]]
        L.append(f"### `{s['name']}` — {s['status']}, domain `{s['domain']}`" + (f", message `{s['message']}`" if "message" in s else ""))
        L.append("")
        L.append(f"Source: {s['source']}. Symbol `{s['symbol']}`.")
        if "note" in s:
            L.append("")
            L.append(s["note"])
        L.append("")
        L.append("```text")
        L.append(g["encodeType"])
        L.append("```")
        L.append("")
        L.append(f"`typeHash` = `{g['typeHash']}`  ")
        L.append(f"Golden vector `hashStruct` = `{g['hashStruct']}`" + (f"  \nGolden vector `digest` = `{g['digest']}`" if "digest" in g else ""))
        L.append("")
    w = golden["permit2Witness"]
    L += ["## Pay Once witness for Permit2 `SignatureTransfer`", "", doc["permit2Witness"]["rule"], "", "```text",
          "witnessTypeString = " + w["witnessTypeString"], "", "single: " + w["typeStringSingle"], "", "batch : " + w["typeStringBatch"], "```", "",
          f"| | value |", "|---|---|", f"| single type hash | `{w['typeHashSingle']}` |", f"| batch type hash | `{w['typeHashBatch']}` |",
          f"| `TokenPermissions` type hash | `{w['tokenPermissionsTypeHash']}` |", "",
          "The strings of the stubs and of `TokenPermissions` are checked against the source of the pinned Permit2 commit by `tools/eip712_types.py`; "
          "the Foundry test `EIP712Permit2.t.sol` has the Permit2 built from that source accept a signature over these strings (single and batch) and reject any change of the string or of a field.", "",
          "## Tags", "", "| Symbol | string | keccak256 |", "|---|---|---|"]
    for k, e in golden["tags"].items():
        L.append(f"| `{k}` | `{e['string']}` | `{e['hash']}` |")
    se = doc["snapshotEncoding"]
    L += ["", "## Migration snapshot encoding", "", f"Status: {se['status']}.", "", se["rule"], "", "```text",
          "\n".join(f"{i + 1:2d}  {n:24s} {s}" for i, (n, s) in enumerate(se["words"])), "```", "",
          f"Golden `termsSnapshotHash` of the golden `MandateTerms` (lineage `{golden['snapshot']['arguments']['lineageId'][:10]}…`, generation {golden['snapshot']['arguments']['generation']}): `{golden['snapshot']['hash']}`.", "",
          "## Versioning policy", "", f"Status: {doc['versioning']['status']}.", ""]
    L += [f"* {r}" for r in doc["versioning"]["rules"]]
    L.append("")
    return "\n".join(L)


# ------------------------------------------------------------------------------------------------------------------ wallet payloads
def gen_typed_data(reg, golden):
    """{file name: json text}: the eth_signTypedData_v4 payload of every signed message, for the wallet lab (WL-16, WL-17, WL-19, WL-27)."""
    out = {}
    values = E.sample_values(reg)
    for s in reg.doc["structs"]:
        n = s["name"]
        if s["domain"] not in ("mandates", "quote"):
            continue
        verifying = E.MANDATE_MANAGER if s["domain"] == "mandates" else E.ROUTER
        payload = E.wallet_payload(reg, n, values[n], s["domain"], E.CHAIN_ID, verifying)
        assert V.hx(E.payload_digest(payload)) == golden["structs"][n]["digest"], f"{n}: the wallet payload does not hash to the golden digest"
        out[n + ".json"] = json.dumps(payload, indent=1) + "\n"
    w = golden["permit2Witness"]
    wv = values["PayOnceIntent"]
    p = w["permit"]
    single = E.permit2_wallet_payload(reg, wv, p["token"], p["amount"], p["spender"], p["nonce"], p["deadline"], E.CHAIN_ID, E.PERMIT2_VECTOR_ADDRESS)
    batch = E.permit2_wallet_payload(reg, wv, p["token"], p["amount"], p["spender"], p["nonce"], p["deadline"], E.CHAIN_ID,
                                     E.PERMIT2_VECTOR_ADDRESS, batch=True, extra=[(w["batchExtra"][0]["token"], w["batchExtra"][0]["amount"])])
    assert V.hx(E.payload_digest(single)) == w["digestSingle"], "PayOnceIntent single payload"
    assert V.hx(E.payload_digest(batch)) == w["digestBatch"], "PayOnceIntent batch payload"
    out["PayOnceIntent.permit2-single.json"] = json.dumps(single, indent=1) + "\n"
    out["PayOnceIntent.permit2-batch.json"] = json.dumps(batch, indent=1) + "\n"
    return out


# ------------------------------------------------------------------------------------------------------------------ main
def render():
    reg = E.Registry(E.load())
    E.self_check(reg)
    golden = E.golden_vectors(reg)
    gj = json.dumps(golden, indent=1, sort_keys=False) + "\n"
    return {
        "sol": gen_solidity(reg),
        "test": gen_golden_test(reg, golden),
        "golden": gj,
        "golden_f": gj,
        "ts": gen_ts(reg, golden),
        "md": gen_md(reg, golden),
    }, golden, gen_typed_data(reg, golden)


def all_files():
    out, golden, typed = render()
    files = {OUT[k]: v for k, v in out.items()}
    files[CONTRACTS_SOL] = out["sol"]
    # the contracts project runs from its own directory: the vectors are read through the path that its fs_permissions allow
    files[CONTRACTS_TEST] = out["test"].replace('vm.readFile("vectors/', 'vm.readFile("../spec/foundry/vectors/')
    for name, text in typed.items():
        files[TYPED / name] = text
        files[TYPED_F / name] = text
    return files


def main(argv):
    files = all_files()
    if "--check" in argv:
        bad = [p for p, v in files.items() if not p.exists() or p.read_text(encoding="utf-8") != v]
        stale = [p for d in (TYPED, TYPED_F) if d.exists() for p in d.glob("*.json") if p not in files]
        if bad or stale:
            print("stale generated artifacts:", ", ".join(str(p.relative_to(ROOT.parent)) for p in bad + stale))
            return 1
        print(f"eip712 artifacts: up to date ({len(files)} files)")
        return 0
    if "--write" in argv:
        for p, v in files.items():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(v, encoding="utf-8", newline="\n")
            print("wrote", p.relative_to(ROOT.parent))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
