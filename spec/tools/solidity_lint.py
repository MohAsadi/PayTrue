#!/usr/bin/env python3
"""A conservative structural checker for the Solidity files of spec/foundry/ (revision 0.5).

There is no Solidity compiler in the authoring environment, so nothing in spec/foundry has been compiled. This tool catches the classes of
mistake that do not need a compiler: a missing brace, a typo in an error or mutant name, a call of a library function that does not exist,
a duplicated function, a test that is not callable. It is NOT a compiler and a clean run proves nothing about the code compiling.

Run:   python -I spec/tools/solidity_lint.py            lint every .sol file under spec/foundry (src, test, lib is skipped)
       python -I spec/tools/solidity_lint.py --list     also print every finding and the inventory

Checks (each finding is an error, exit code 1):
  1  SPDX line present and identical in every file; exactly one `pragma solidity` identical in every file
  2  no tab characters; no trailing carriage returns in the middle of a line
  3  braces, parentheses and brackets are balanced and properly nested, outside comments and strings
  4  every import path is a forge-std path or a relative path that resolves to a file inside spec/foundry
  5  every `test*` and `invariant_*` function is public or external; not pure or view when it asserts
  6  no function is declared twice with the same parameters in one contract or library (overloads with other parameters are fine)
  7  banned identifiers: tx.origin, selfdestruct, delegatecall, callcode, suicide, assembly, `unchecked` (unless the line says
     `lint: allow unchecked`), `assembly` (unless the line says `lint: allow assembly`), `now`, `block.difficulty`, `.send(`, `.transfer(` on addresses
  8  every `revert Name(` and every `Name.selector` names an error that is declared (src/Errors.sol or the same file), or a contract,
     library, interface or event
  9  every `M_*` mutant constant used is defined in src/Mutants.sol; every `OP_*`, `ACT_*` constant is defined in test/generated/GenOps.sol
 10  every `Library.member` of the model libraries exists in that library; every `fx.member` call exists in the Fixture
 11  the generated files carry the header `// GENERATED by tools/export_foundry.py from ...; do not edit`
 12  address literals: no 40-digit hex literal used as an address or integer (the compiler checks them as EIP-55 addresses)
"""
import pathlib
import re
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

SPEC = pathlib.Path(__file__).resolve().parent.parent
FOUNDRY = SPEC / "foundry"
LIBS = ("HashModel", "PinModel", "ContainModel", "TimeModel", "WidthLib", "AllowanceMath", "GenErrorIds", "GenManifest", "VectorSuite",
        "SignerChecks")
BANNED = [(r"\btx\.origin\b", "tx.origin"), (r"\bselfdestruct\b", "selfdestruct"), (r"\bdelegatecall\b", "delegatecall"),
          (r"\bcallcode\b", "callcode"), (r"\bsuicide\b", "suicide"), (r"\bassembly\b", "assembly"), (r"\bblock\.difficulty\b", "block.difficulty"),
          (r"\.send\(", ".send("), (r"\bnow\b", "now")]
KEYWORD_LIKE = {"super", "this", "type", "abi", "msg", "block", "tx", "bytes", "string", "address", "uint256"}


def strip(text):
    """Return (code, ok): the text with comments and string contents replaced by spaces (same length), for structural checks."""
    out = []
    i, n = 0, len(text)
    state = None
    quote = ""
    ok = True
    while i < n:
        c = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if state is None:
            if c == "/" and nxt == "/":
                state = "line"
                out.append("  ")
                i += 2
                continue
            if c == "/" and nxt == "*":
                state = "block"
                out.append("  ")
                i += 2
                continue
            if c in "\"'":
                state, quote = "str", c
                out.append(c)
                i += 1
                continue
            out.append(c)
            i += 1
        elif state == "line":
            if c == "\n":
                state = None
                out.append("\n")
            else:
                out.append(" ")
            i += 1
        elif state == "block":
            if c == "*" and nxt == "/":
                state = None
                out.append("  ")
                i += 2
                continue
            out.append("\n" if c == "\n" else " ")
            i += 1
        else:  # string
            if c == "\\":
                out.append("  ")
                i += 2
                continue
            if c == quote:
                state = None
                out.append(c)
                i += 1
                continue
            if c == "\n":
                ok = False
                state = None
                out.append("\n")
                i += 1
                continue
            out.append(" ")
            i += 1
    if state in ("str", "block"):
        ok = False
    return "".join(out), ok


def balanced(code):
    pairs = {")": "(", "]": "[", "}": "{"}
    stack = []
    line = 1
    for ch in code:
        if ch == "\n":
            line += 1
        elif ch in "([{":
            stack.append((ch, line))
        elif ch in ")]}":
            if not stack or stack[-1][0] != pairs[ch]:
                return f"unbalanced '{ch}' at line {line}"
            stack.pop()
    if stack:
        return f"unclosed '{stack[-1][0]}' opened at line {stack[-1][1]}"
    return None


def blocks(code):
    """Yield (kind, name, start, end) for every contract, library and interface (end = index of the closing brace)."""
    for m in re.finditer(r"\b(abstract\s+contract|contract|library|interface)\s+(\w+)[^{;]*\{", code):
        depth, i = 1, m.end()
        while i < len(code) and depth:
            if code[i] == "{":
                depth += 1
            elif code[i] == "}":
                depth -= 1
            i += 1
        yield m.group(1).split()[-1], m.group(2), m.end(), i - 1


def function_headers(code, start, end):
    """(name, header) for every function declared directly in code[start:end] (header = text from `function` to the `{` or `;`)."""
    out = []
    for m in re.finditer(r"\bfunction\s+(\w+)\s*\(", code[start:end]):
        i = start + m.start()
        j = i
        depth = 0
        while j < end:
            ch = code[j]
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch in "{;" and depth == 0:
                break
            j += 1
        out.append((m.group(1), code[i:j], code.count("\n", 0, i) + 1))
    return out


def members(code, start, end):
    """The names a library or contract offers: functions, constants, structs, enums, public variables, events, errors."""
    body = code[start:end]
    names = set(re.findall(r"\bfunction\s+(\w+)", body))
    names |= set(re.findall(r"\b(\w+)\s*=\s*[^=;]*;", re.sub(r"\bfunction\b[^{]*\{", "", body)) if False else [])
    names |= set(re.findall(r"\bconstant\s+(\w+)\s*=", body))
    names |= set(re.findall(r"\b(?:struct|enum|event|error)\s+(\w+)", body))
    names |= set(re.findall(r"\b(?:public|external)\s+(?:immutable\s+)?(\w+)\s*(?:=|;)", body))
    names |= set(re.findall(r"\bpublic\s+(?:constant\s+|immutable\s+)?(\w+)\s*=", body))
    names |= set(re.findall(r"\bmapping\s*\([^;]*\)\s*public\s+(\w+)\s*;", body))
    names |= set(re.findall(r"\b[A-Za-z0-9_\[\]\.]+\s+public\s+(\w+)\s*;", body))
    names |= set(re.findall(r"\b[A-Za-z0-9_\[\]\.]+\s+public\s+(?:constant|immutable)\s+(\w+)\s*=", body))
    return names


def main():
    list_all = "--list" in sys.argv
    files = sorted(p for p in FOUNDRY.rglob("*.sol") if not any(part in ("lib", "out", "cache") for part in p.relative_to(FOUNDRY).parts))
    errors = []

    def err(path, line, msg):
        errors.append(f"{path.relative_to(SPEC).as_posix()}:{line}: {msg}")

    if not files:
        print("solidity_lint: no .sol files under spec/foundry")
        return 1
    texts = {p: p.read_bytes().decode("utf-8").replace("\r\n", "\n") for p in files}
    codes = {}
    spdx, pragma = {}, {}
    declared_errors, defined_mutants, defined_ops = set(), set(), set()
    lib_members, contract_members = {}, {}
    type_names = set()
    totals = dict(lines=0, contracts=0, functions=0, tests=0, invariants=0)

    for p in files:
        t = texts[p]
        code, ok = strip(t)
        codes[p] = code
        totals["lines"] += t.count("\n")
        if not ok:
            err(p, 1, "unterminated string or block comment")
        first = t.split("\n", 1)[0]
        m = re.match(r"// SPDX-License-Identifier: (\S.*)$", first)
        if not m:
            err(p, 1, "the first line must be `// SPDX-License-Identifier: ...`")
        else:
            spdx[p] = m.group(1).strip()
        pm = re.findall(r"^pragma solidity ([^;]+);", code, re.M)
        if len(pm) != 1:
            err(p, 1, f"expected exactly one `pragma solidity`, found {len(pm)}")
        else:
            pragma[p] = pm[0].strip()
        if "\t" in t:
            err(p, t[:t.index("\t")].count("\n") + 1, "tab character")
        if "\r" in t:
            err(p, t[:t.index("\r")].count("\n") + 1, "carriage return inside the file")
        bal = balanced(code)
        if bal:
            err(p, 1, bal)
        for name in re.findall(r"^\s*error\s+(\w+)\s*\(", code, re.M):
            declared_errors.add(name)
        for name in re.findall(r"\bM_(\w+)\s*=", code):
            if p.name == "Mutants.sol":
                defined_mutants.add("M_" + name)
        if p.name == "GenOps.sol":
            defined_ops |= set(re.findall(r"\bconstant\s+((?:OP|ACT)_\w+)\s*=", code))
        for kind, name, s, e in blocks(code):
            type_names.add(name)
            totals["contracts"] += 1
            if kind == "library":
                lib_members[name] = members(code, s, e)
            else:
                contract_members[name] = members(code, s, e)
        type_names |= set(re.findall(r"\bevent\s+(\w+)", code))
        type_names |= set(re.findall(r"\bstruct\s+(\w+)", code))
    if len(set(spdx.values())) > 1:
        errors.append(f"SPDX identifiers differ: {sorted(set(spdx.values()))}")
    if len(set(pragma.values())) > 1:
        errors.append(f"pragma versions differ: {sorted(set(pragma.values()))}")

    for p in files:
        t, code = texts[p], codes[p]
        rel = p.relative_to(FOUNDRY).as_posix()
        # imports
        for m in re.finditer(r'import\s+(?:[^"\n]*?from\s+)?"([^"]+)"\s*;', t):
            path = m.group(1)
            line = t[:m.start()].count("\n") + 1
            if path.startswith("forge-std/"):
                continue
            if not path.startswith("."):
                err(p, line, f"import path {path!r} is neither forge-std nor relative")
                continue
            target = (p.parent / path).resolve()
            try:
                target.relative_to(FOUNDRY.resolve())
            except ValueError:
                err(p, line, f"import {path!r} leaves spec/foundry")
                continue
            if not target.exists():
                err(p, line, f"import {path!r} does not resolve to a file")
        # functions: test visibility, duplicates
        for kind, name, s, e in blocks(code):
            seen = {}
            for fname, header, line in function_headers(code, s, e):
                totals["functions"] += 1
                params = re.sub(r"\s+", " ", header[header.index("(") + 1:header.index(")")]) if "(" in header and ")" in header else ""
                sig = (fname, re.sub(r"\b\w+(?=\s*(,|$))", "", params) if False else params)
                if fname in seen and kind != "interface" and seen[fname][1] == sig[1]:
                    err(p, line, f"function {fname} is declared twice in {name} (first at line {seen[fname][0]})")
                seen.setdefault(fname, (line, sig[1]))   # an overload with other parameters is not a duplicate
                if fname.startswith("test"):
                    totals["tests"] += 1
                if fname.startswith("invariant_"):
                    totals["invariants"] += 1
                if fname.startswith("test") or fname.startswith("invariant_"):
                    if not re.search(r"\b(public|external)\b", header):
                        err(p, line, f"{fname} must be public or external")
                    if re.search(r"\b(pure|view)\b", header) and "/generated/" not in "/" + rel:
                        body_start = code.index("{", code.index(header) + len(header) - 1) if "{" in code[code.index(header):code.index(header) + len(header) + 2] else None
                        if body_start is not None:
                            depth, i = 1, body_start + 1
                            while i < len(code) and depth:
                                depth += (code[i] == "{") - (code[i] == "}")
                                i += 1
                            if re.search(r"\bassert\w*\(", code[body_start:i]):
                                err(p, line, f"{fname} calls an assertion and must not be pure or view")
        # banned identifiers
        for pat, label in BANNED:
            for m in re.finditer(pat, code):
                ln = code[:m.start()].count("\n") + 1
                if label == "assembly" and "lint: allow assembly" in t.split("\n")[ln - 1]:
                    continue                                      # memory reads and reverts in tests, marked on the line
                err(p, ln, f"banned: {label}")
        for m in re.finditer(r"\bunchecked\b", code):
            line = code[:m.start()].count("\n") + 1
            if "lint: allow unchecked" not in t.split("\n")[line - 1]:
                err(p, line, "unchecked block without `lint: allow unchecked`")
        for m in re.finditer(r"\.transfer\(", code):
            err(p, code[:m.start()].count("\n") + 1, "banned: .transfer( (an address transfer)")
        # errors and selectors
        local_errors = set(re.findall(r"^\s*error\s+(\w+)\s*\(", code, re.M))
        for m in re.finditer(r"\brevert\s+(\w+)\s*\(", code):
            name = m.group(1)
            if name not in declared_errors and name not in local_errors:
                err(p, code[:m.start()].count("\n") + 1, f"revert {name}(...): no such error is declared")
        for m in re.finditer(r"\b([A-Z]\w*)\.selector\b", code):
            name = m.group(1)
            if name not in declared_errors and name not in local_errors and name not in type_names:
                err(p, code[:m.start()].count("\n") + 1, f"{name}.selector: not an error, contract, interface or event of this project")
        # mutants and ops
        if p.name != "Mutants.sol":
            for m in re.finditer(r"\bM_[A-Z0-9_]+\b", code):
                if m.group(0) not in defined_mutants:
                    err(p, code[:m.start()].count("\n") + 1, f"{m.group(0)} is not defined in src/Mutants.sol")
        for m in re.finditer(r"\b((?:OP|ACT)_[A-Z0-9_]+)\b", code):
            if p.name != "GenOps.sol" and m.group(1) not in defined_ops:
                err(p, code[:m.start()].count("\n") + 1, f"{m.group(1)} is not defined in test/generated/GenOps.sol")
        # library members and Fixture calls
        for m in re.finditer(r"\b(" + "|".join(LIBS) + r")\.(\w+)", code):
            lib, member = m.group(1), m.group(2)
            if lib in lib_members and member not in lib_members[lib]:
                err(p, code[:m.start()].count("\n") + 1, f"{lib}.{member} does not exist")
        fixture = contract_members.get("Fixture", set())
        scen = contract_members.get("ScenarioVM", set())
        if fixture:
            for m in re.finditer(r"\bfx\.(\w+)\(", code):
                if m.group(1) not in fixture:
                    err(p, code[:m.start()].count("\n") + 1, f"fx.{m.group(1)}(...): not a member of Fixture")
        if scen:
            for m in re.finditer(r"\bmachine\.(\w+)\(", code):
                if m.group(1) not in scen:
                    err(p, code[:m.start()].count("\n") + 1, f"machine.{m.group(1)}(...): not a member of ScenarioVM")
        # address literals: 40 hex digits (a 42-digit literal with leading zeros is the accepted form)
        for m in re.finditer(r"\b0x[0-9a-fA-F]{40}\b", code):
            if re.search(r"[a-fA-F]", m.group(0)[2:]):          # a digits-only literal passes the checksum trivially
                err(p, code[:m.start()].count("\n") + 1, "40-digit hex literal with letters: the compiler checks it as an EIP-55 address (use 42 digits or a bytes32)")
        # generated header
        if "/generated/" in "/" + rel or rel in ("src/Errors.sol", "src/Mutants.sol"):
            if not re.search(r"^// GENERATED by tools/export_(foundry|eip712)\.py from .+; do not edit$", t, re.M):
                err(p, 2, "generated file without the `// GENERATED by tools/export_foundry.py (or export_eip712.py) from <source>; do not edit` header")

    inventory = (f"{len(files)} files, {totals['lines']} lines, {totals['contracts']} contracts/libraries/interfaces, "
                 f"{totals['functions']} functions, {totals['tests']} test functions, {totals['invariants']} invariants")
    if list_all or errors:
        for e in errors:
            print("  " + e)
    if errors:
        print(f"solidity_lint: {len(errors)} findings in {inventory}")
        return 1
    print(f"solidity_lint: ok - {inventory}; pragma {next(iter(set(pragma.values())), '?')}, SPDX {next(iter(set(spdx.values())), '?')} "
          f"(a structural check only: nothing here has been compiled)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
