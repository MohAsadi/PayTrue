// Writes (or checks) docs/configuration.md from the schema of @paytrue/config, so the reference can never drift from the code.
//
//   node packages/config/scripts/generate-config-doc.mjs           write docs/configuration.md
//   node packages/config/scripts/generate-config-doc.mjs --check   exit 1 if the file differs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ENV_SCHEMA, GROUPS } from "../src/schema.js";

const cell = (s) => String(s ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");

export function renderConfigDoc() {
  const out = [
    "# Configuration reference",
    "",
    "> GENERATED by `packages/config/scripts/generate-config-doc.mjs` from `packages/config/src/schema.js`. Do not edit by hand: change the schema and regenerate.",
    "> `.env.example` is generated from the same schema.",
    "",
    "PayTrue is configured through environment variables that start with `PAYTRUE_`. Every variable below is read by code in this repository: the configuration loader",
    "(`@paytrue/config`), the development stub, or the contract deployment script. **No variable has a default that points at a PayTrue-hosted service**, and Cloud is off",
    "unless you turn it on and give it an address yourself.",
    "",
    "`PAYTRUE_ENV=production` is strict: it refuses http origins, local addresses, a missing public origin, fewer than two RPC hosts per chain, and the development stub.",
    "",
  ];
  for (const [group, title] of Object.entries(GROUPS)) {
    out.push(`## ${title}`, "", "| Variable | Default | Required | Description |", "|---|---|---|---|");
    for (const v of ENV_SCHEMA.filter((x) => x.group === group)) {
      const name = `\`${v.name}\`${v.secret ? " (secret)" : ""}`;
      out.push(`| ${name} | ${cell(v.default ?? "none")} | ${cell(v.requiredWhen ?? "no")} | ${cell(v.description)} |`);
    }
    out.push("");
  }
  out.push(
    "## Layouts",
    "",
    "The same variables describe every layout (see [domains](domains.md)):",
    "",
    "| Layout | `PAYTRUE_PUBLIC_ORIGIN` | `PAYTRUE_BASE_PATH` | Other |",
    "|---|---|---|---|",
    "| A path on a domain you already serve | `https://example.com` | `/paytrue` | `PAYTRUE_PROXY_STRIPS_BASE_PATH` matches your proxy |",
    "| Your own subdomain (recommended) | `https://pay.example.com` | `/` | |",
    "| Hosted checkout and API on different hosts | `https://shop.example.com` | `/paytrue` | `PAYTRUE_CHECKOUT_ORIGIN`, `PAYTRUE_CHECKOUT_BASE_PATH`, `PAYTRUE_API_ORIGIN`, `PAYTRUE_API_BASE_PATH` |",
    "| Embedded in another frontend | as above | as above | `PAYTRUE_ALLOWED_FRAME_ANCESTORS`, `PAYTRUE_COOKIE_SAMESITE` (see [embedding](embedding.md)) |",
    "",
  );
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL("../../../docs/configuration.md", import.meta.url);
  const text = renderConfigDoc();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
    } catch {
      /* missing */
    }
    if (current !== text) {
      console.error("docs/configuration.md is not up to date: run `node packages/config/scripts/generate-config-doc.mjs`");
      process.exit(1);
    }
    console.log("docs/configuration.md is up to date");
  } else {
    writeFileSync(target, text);
    console.log("wrote docs/configuration.md");
  }
}
