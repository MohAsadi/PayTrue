// Writes (or checks) the repository's `.env.example` from the schema of @paytrue/config, so that the example can never drift from the code.
//
//   node packages/config/scripts/generate-env-example.mjs           write .env.example
//   node packages/config/scripts/generate-env-example.mjs --check   exit 1 if .env.example differs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ENV_SCHEMA, GROUPS } from "../src/schema.js";

export function renderEnvExample() {
  const lines = [
    "# PayTrue environment example. GENERATED by packages/config/scripts/generate-env-example.mjs from packages/config/src/schema.js; do not edit by hand.",
    "# Copy to `.env` (which is ignored by Git) and change the values. Never commit secrets.",
    "# A line that starts with `#` shows the default or an example; uncomment it to set it. Names with <chainId> stand for one variable per chain.",
    "",
  ];
  for (const [group, title] of Object.entries(GROUPS)) {
    lines.push(`# ---- ${title}`);
    for (const v of ENV_SCHEMA.filter((x) => x.group === group)) {
      lines.push(`# ${v.description}`);
      if (v.requiredWhen) lines.push(`# Required: ${v.requiredWhen}.`);
      if (v.default !== undefined) lines.push(`# Default: ${v.default}`);
      if (v.secret) lines.push("# SECRET: keep it out of Git and out of logs.");
      lines.push(`# ${v.name}=${v.example ?? ""}`);
      lines.push("");
    }
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL("../../../.env.example", import.meta.url);
  const text = renderEnvExample();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
    } catch {
      /* missing */
    }
    if (current !== text) {
      console.error(".env.example is not up to date: run `node packages/config/scripts/generate-env-example.mjs`");
      process.exit(1);
    }
    console.log(".env.example is up to date");
  } else {
    writeFileSync(target, text);
    console.log("wrote .env.example");
  }
}
